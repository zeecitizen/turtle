"""Build mt5/saad_vsisa_diamond_hybrid.mq5 (Zee 2026-10-14: "this EA with $288,367, compile it and run ML algos on
it to tune it to higher profit") from svh_diamond.mq5 (build_svh_diamond.py) with the $288,367 setting as defaults:
Saad x2 lots when VSISA SAW a same-direction setup within 240 min (InpHybSaadGate 3), Diamond only during a
same-direction Saad/VSISA trade (InpHybDiaGate 2). Own magics 88360 Saad / 88361 VSISA / 88362 Diamond.
    py build_svd.py [--params tuned.json]      (tuned.json: {"InpName": value, ...} overrides defaults)"""
import json, re, sys
from pathlib import Path

M = Path(r'C:\Users\zeesh\turtle\mt5')
VER = "1.00"
over = json.loads(Path(sys.argv[sys.argv.index('--params') + 1]).read_text()) if '--params' in sys.argv else {}
if over.get('_ver'): VER = over.pop('_ver')
C = f"SVDia v{VER}"


def rep_in(txt, a, b):
    assert txt.count(a) == 1, (txt.count(a), a[:80])
    return txt.replace(a, b)


def set_default(txt, name, val):
    """Replace the default of `input <type> name = X;` wherever it lives."""
    pat = re.compile(rf'^(input\s+(\w+)\s+{name}\s*=\s*)([^;]+);', re.M)
    m = pat.search(txt)
    if not m: return txt, False
    typ = m.group(2)
    v = ("true" if val in (1, True, "true") else "false") if typ == "bool" else (str(int(val)) if typ in ("int", "long") else repr(float(val)))
    return txt[:m.start()] + m.group(1) + v + ";" + txt[m.end():], True


sa = (M / 'saad_vsisa_hybrid_saad.mqh').read_text(encoding='utf-8')
sa = rep_in(sa, 'input int    S_InpMagicNumber = 88350;', 'input int    S_InpMagicNumber = 88360;')
sa = rep_in(sa, '#define S_EA_COMMENT "SVHyb v1.00 SAAD"', f'#define S_EA_COMMENT "{C} SAAD"')
di = (M / 'DiamondEngineM1.mqh').read_text(encoding='utf-8')
di = rep_in(di, 'input int    D_InpMagicNumber = 88352;', 'input int    D_InpMagicNumber = 88362;')
di = di.replace('"SVHyb DIA %s D%d"', f'"{C} DIA %s D%d"')
s = (M / 'svh_diamond.mq5').read_text(encoding='utf-8')
s = rep_in(s, '#include "saad_vsisa_hybrid_saad.mqh"', '#include "svd_saad.mqh"')
s = rep_in(s, '#include "DiamondEngineM1.mqh"', '#include "svd_diamond.mqh"')
s = rep_in(s, 'input int    InpMagicNumber = 88351;', 'input int    InpMagicNumber = 88361;')
s = s.replace('"SVHyb v1.00 VSISA %d_%d"', f'"{C} VSISA %d_%d"')
s = s.replace('svh_diamond (research) | VSISA part', f'saad_vsisa_diamond_hybrid v{VER} | VSISA part')
s = rep_in(s, 'input group "=== saad_vsisa_hybrid: both trade; Saad x2 lots when VSISA traded the same way <= 60 min ==="',
           'input group "=== saad_vsisa_diamond_hybrid: Saad + VSISA + UHV Diamond ==="')
base = {"InpHybSaadGate": 3, "InpHybWinMin": 240, "InpHybDiaGate": 2}
base.update(over)
for k, v in base.items():
    done = False
    for name in ('s', 'sa', 'di'):
        t = {'s': s, 'sa': sa, 'di': di}[name]
        t, ok = set_default(t, k, v)
        if ok:
            if name == 's': s = t
            elif name == 'sa': sa = t
            else: di = t
            done = True; break
    assert done, f'input {k} not found'
s = re.sub(r'#property version\s+"[^"]*"', f'#property version   "{VER}"', s, count=1)
s = ('//+------------------------------------------------------------------+\n'
     f'//| saad_vsisa_diamond_hybrid v{VER} - attach on XAUUSD M5.            |\n'
     '//| Saad 15-min (88360) + VSISA 5-min (88361) + UHV Diamond M1 (88362) |\n'
     '//| Saad trades at x InpHybConfMult lots when VSISA confirmed (gate);  |\n'
     '//| Diamond fires only during a same-direction Saad/VSISA trade.       |\n'
     '//| Needs svd_saad.mqh, svd_diamond.mqh + 4 Vsisa*.mqh next to it.     |\n'
     '//| GENERATED by monitor/strategy_lab/build_svd.py.                    |\n'
     '//+------------------------------------------------------------------+\n') + s
(M / 'svd_saad.mqh').write_text(sa, encoding='utf-8')
(M / 'svd_diamond.mqh').write_text(di, encoding='utf-8')
(M / 'saad_vsisa_diamond_hybrid.mq5').write_text(s, encoding='utf-8')
print(f'saad_vsisa_diamond_hybrid v{VER} built', base)
