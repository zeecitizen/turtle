def prefix_engine(src, P):
    """Like build_svh_diamond.prefix_engine, but also catches EVERY declaration on a line ('int a; double b;')."""
    body = src[src.index('#include <Trade/Trade.mqh>'):].replace('#include <Trade/Trade.mqh>\n', '')
    names = set()
    names |= set(re.findall(r'^input\s+\w+\s+(\w+)', body, re.M))
    names |= set(re.findall(r'^(?:struct|enum|class)\s+(\w+)', body, re.M))
    names |= set(re.findall(r'^#define\s+(\w+)', body, re.M))
    for m in re.finditer(r'^(?:static\s+)?(?:const\s+)?[A-Za-z_]\w*(?:\s*\[\])?\s+[A-Za-z_]\w*\s*\(', body, re.M):
        names.add(re.search(r'([A-Za-z_]\w*)\s*\($', m.group(0)).group(1))
    types = set(re.findall(r'^(?:struct|enum|class)\s+(\w+)', body, re.M)) | {
        'int', 'double', 'bool', 'string', 'datetime', 'ulong', 'long', 'uint', 'color', 'CTrade', 'float', 'short', 'char', 'uchar'}
    tre = re.compile(r'^\s*(?:static\s+)?(?:' + '|'.join(sorted(types)) + r')\s+([^(]+)$')
    for line in body.splitlines():
        if not line or line[0].isspace():
            continue
        code = re.sub(r'"(?:[^"\\]|\\.)*"', '""', line).split('//')[0]      # string literals out first
        if '(' in code and not re.match(r'^(?:' + '|'.join(sorted(types)) + r')\s+\w+(?:\[\d*\])?\s*=', code):
            continue
        for seg in code.split(';'):
            m = tre.match(seg)
            if not m: continue
            for part in re.sub(r'\{[^}]*\}', '', m.group(1)).split(','):
                nm = re.match(r'\s*([A-Za-z_]\w*)', part)
                if nm: names.add(nm.group(1))
    names -= {'if', 'for', 'while', 'switch', 'return', 'else', 'input'}
    for n in sorted(names, key=len, reverse=True):
        body = re.sub(rf'(?<![\w.]){n}\b', P + n, body)
    return body, names
src = (M / 'VSISA.mq5').read_text(encoding='utf-8').replace('\ufeff', '')
