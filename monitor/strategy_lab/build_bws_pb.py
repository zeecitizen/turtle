"""bws_pb.mqh: VSISA_Pullbacks as a 4th signal scout for bread_winner (prefix P_, timeframe input P_InpTF, magic
88394). Its Fire() reports to the host (BwPbHook) and never trades on its own."""
import re, sys
from pathlib import Path
sys.argv = [sys.argv[0]]
from build_svh_diamond import prefix_engine   # (importing rebuilds svh_diamond files unchanged)

M = Path(r'C:\Users\zeesh\turtle\mt5')
src = (M / 'VSISA_Pullbacks.mq5').read_text(encoding='utf-8').replace('\ufeff', '')
body, names = prefix_engine(src, 'P_')
tfv = 'P_InpTF'
body = (body.replace('PeriodSeconds()', f'PeriodSeconds({tfv})').replace('PERIOD_CURRENT', tfv)
        .replace('(ENUM_TIMEFRAMES)Period()', tfv).replace('Period()', tfv).replace('_Period', tfv))


def setdef(txt, name, val):
    pat = re.compile(rf'^(input\s+\w+\s+{name}\s*=\s*)([^;]+);', re.M)
    assert len(pat.findall(txt)) == 1, name
    return pat.sub(lambda m: m.group(1) + val + ';', txt)


body = setdef(body, 'P_InpMagicNumber', '88394')
for k, v in {'P_InpLots': '0.01'}.items():
    body = setdef(body, k, v)
a = 'void P_Fire(int side, double sl_level, string why) {\n'
assert body.count(a) == 1
body = body.replace(a, a + '   if (BwPbHook(side, sl_level)) return;\n')
hdr = ('//+------------------------------------------------------------------+\n'
       '//| VSISA_Pullbacks.mq5 as a signal scout for bread_winner            |\n'
       '//| GENERATED by build_bws_pb.py: names prefixed P_, TF = P_InpTF.    |\n'
       '//+------------------------------------------------------------------+\n'
       'input group "=== VSISA PULLBACKS scout ==="\n'
       f'input ENUM_TIMEFRAMES {tfv} = PERIOD_M5;   // {tfv} — this engine\'s candles\n')
(M / 'bws_pb.mqh').write_text(hdr + body, encoding='utf-8')
print(f'bws_pb.mqh: {len(names)} names prefixed')
