"""Build mt5/Saad_regime.mq5 = Saad_meta + market-regime adaptation (Zee 2026-10-13, "Option 2: Unsupervised
Market Regime Detection"). Nothing is vetoed by a model; the regime only changes settings:
  TREND  (GMM cluster with the highest mean ER): no breakeven at TP1, old exit = ATR trail x InpRegTrendAtr, chop ER InpRegTrendEr
  CHOP   (lowest mean ER): breakeven at TP1, the $ trail, chop ER InpRegChopEr
  NORMAL (the other):      breakeven at TP1, the $ trail, chop ER InpRegNormEr
The regime of the candle that just closed is computed in the EA from ER(14), ATR14/ATR200 and the
14-candle realized volatility, with the GMM compiled in (SaadRegimeModel.mqh, generated by
meta_labeling_system/src/train_regime_gmm.py). A position keeps the regime it was opened in.
InpRegimeLog writes those three features + the regime for every closed candle (training data)."""
src = r'C:\Users\zeesh\turtle\mt5\Saad_meta.mq5'
dst = r'C:\Users\zeesh\turtle\mt5\Saad_regime.mq5'
s = open(src, encoding='utf-8').read()


def rep(a, b, n=1):
    global s
    assert s.count(a) == n, (s.count(a), a[:80])
    s = s.replace(a, b)


rep('#include "SaadMetaModel.mqh"', '#include "SaadMetaModel.mqh"\n#include "SaadRegimeModel.mqh"')
rep("input int    InpMetaMode    = 0;",
    """input int    InpRegimeMode  = 0;      // InpRegimeMode — market-regime adaptation: 0 off · 1 GMM compiled into the EA
input bool   InpRegimeLog   = false;  // InpRegimeLog — log ER / ATR ratio / realized vol + regime of every closed candle to Common\\Files\\saad_regime_<InpMetaTag>.csv
input double InpRegTrendEr  = 0.10;   // InpRegTrendEr — TREND regime: chop filter ER
input bool   InpRegTrendBe  = false;  // InpRegTrendBe — TREND regime: breakeven at TP1
input bool   InpRegTrendAtrExit = true; // InpRegTrendAtrExit — TREND regime: after TP1 trail by ATR (old exit) instead of the $ trail
input double InpRegTrendAtr = 2.5;    // InpRegTrendAtr — TREND regime: ATR trail multiple
input double InpRegChopEr   = 0.35;   // InpRegChopEr — CHOP regime: chop filter ER
input double InpRegNormEr   = 0.15;   // InpRegNormEr — NORMAL regime: chop filter ER
input int    InpMetaMode    = 0;""")
rep("int num; double slNow;", "int reg; int num; double slNow;")
rep("int g_metaVeto = 0;", """int g_metaVeto = 0;
int g_regime = -1;                   // regime of the candle that just closed (-1 = unknown / off)
int g_regBars[3] = {0, 0, 0};
int g_regLog = INVALID_HANDLE;
bool RegOn() { return InpRegimeMode > 0 && g_regime >= 0; }
bool IsTrend(int r) { return InpRegimeMode > 0 && r == REG_TREND; }
double ChopErNow() { if (!RegOn()) return InpChopEr; return g_regime == REG_TREND ? InpRegTrendEr : g_regime == REG_CHOP ? InpRegChopEr : InpRegNormEr; }
bool Tp1BeFor(int r) { return IsTrend(r) ? InpRegTrendBe : InpTp1Be; }
int LongTouchFor(int r) { return IsTrend(r) && InpRegTrendAtrExit ? 0 : InpLongTouch; }
int ShortTouchFor(int r) { return IsTrend(r) && InpRegTrendAtrExit ? 0 : InpShortTouch; }
double TrailAtrFor(int r) { return IsTrend(r) && InpRegTrendAtrExit ? InpRegTrendAtr : InpTrailAtr; }""")

# features + GMM on each new candle
rep("bool Choppy()\n{", r'''// the three regime features of the candle that just closed
bool RegFeatures(double &x[])
{
   ArrayResize(x, 3);
   double atr = Buf(hAtr, 1), atr200 = Buf(hAtr200, 1);
   if (atr <= 0 || atr200 <= 0) return false;
   double net = MathAbs(iClose(_Symbol, PERIOD_CURRENT, 1) - iClose(_Symbol, PERIOD_CURRENT, 15)), path = 0, r[14], m = 0;
   for (int i = 1; i <= 14; i++) {
      double a = iClose(_Symbol, PERIOD_CURRENT, i), b = iClose(_Symbol, PERIOD_CURRENT, i + 1);
      if (a <= 0 || b <= 0) return false;
      path += MathAbs(a - b); r[i - 1] = MathLog(a / b); m += r[i - 1];
   }
   m /= 14; double v = 0; for (int i = 0; i < 14; i++) v += (r[i] - m) * (r[i] - m);
   x[0] = path > 0 ? net / path : 0;          // Kaufman ER (14)
   x[1] = atr / atr200;                       // ATR14 / ATR200
   x[2] = MathSqrt(v / 13);                   // realized vol: std of 14 log returns (sample)
   return true;
}
void RegimeUpdate()
{
   if (InpRegimeMode <= 0 && !InpRegimeLog) return;
   double x[];
   if (!RegFeatures(x)) { g_regime = -1; return; }
   g_regime = RegimeOf(x);
   if (g_regime >= 0 && g_regime < 3) g_regBars[g_regime]++;
   if (InpRegimeLog) {
      if (g_regLog == INVALID_HANDLE) {
         string fn = StringFormat("saad_regime_%d.csv", InpMetaTag);
         if (MQLInfoInteger(MQL_TESTER)) FileDelete(fn, FILE_COMMON);
         g_regLog = FileOpen(fn, FILE_READ | FILE_WRITE | FILE_TXT | FILE_COMMON | FILE_SHARE_READ | FILE_ANSI);
         if (g_regLog != INVALID_HANDLE) { FileSeek(g_regLog, 0, SEEK_END); if (FileSize(g_regLog) == 0) FileWriteString(g_regLog, "time,kaufman_er,atr_ratio,realized_vol,regime\r\n"); }
      }
      if (g_regLog != INVALID_HANDLE)
         FileWriteString(g_regLog, StringFormat("%s,%.8f,%.8f,%.10f,%d\r\n", TimeToString(iTime(_Symbol, PERIOD_CURRENT, 1), TIME_DATE | TIME_MINUTES), x[0], x[1], x[2], g_regime));
   }
}

bool Choppy()
{''')
rep("   if (InpChopEr <= 0) return false;\n", "   double erMin = ChopErNow();\n   if (erMin <= 0) return false;\n")
rep("   return path <= 0 || net / path < InpChopEr;", "   return path <= 0 || net / path < erMin;")
rep("      g_lastBar = bar;\n", "      g_lastBar = bar;\n      RegimeUpdate();\n")

# per-position regime
rep("   if (InpTp1Be && g_pos[i].entry < bid)", "   if (Tp1BeFor(g_pos[i].reg) && g_pos[i].entry < bid)")
rep("   if (InpTp1Be && g_pos[i].entry > ask)", "   if (Tp1BeFor(g_pos[i].reg) && g_pos[i].entry > ask)")
rep("      if (InpLongTouch == 1 && g_pos[i].side > 0", "      if (LongTouchFor(g_pos[i].reg) == 1 && g_pos[i].side > 0")
rep("InpShortTouch == 1 && bid <= g_pos[i].tp)", "ShortTouchFor(g_pos[i].reg) == 1 && bid <= g_pos[i].tp)")
rep("InpFixTpPips <= 0 && InpLongTouch == 0) {", "InpFixTpPips <= 0 && LongTouchFor(g_pos[i].reg) == 0) {")
rep("g_pos[i].best - InpTrailAtr * Buf(hAtr, 1) : g_pos[i].best + InpTrailAtr * Buf(hAtr, 1);",
    "g_pos[i].best - TrailAtrFor(g_pos[i].reg) * Buf(hAtr, 1) : g_pos[i].best + TrailAtrFor(g_pos[i].reg) * Buf(hAtr, 1);")
rep("      if (noTp && InpLongResTp1 && InpLongTouch == 1) {", "      if (noTp && InpLongResTp1 && LongTouchFor(g_regime) == 1) {")
# set p.reg on both creation paths (entry: the current regime; adopted after restart: unknown)
rep("   p.entryTime = TimeCurrent(); p.best = p.entry;\n", "   p.entryTime = TimeCurrent(); p.best = p.entry; p.reg = g_regime;\n")
rep("p.entryTime = (datetime)PositionGetInteger(POSITION_TIME); p.best = p.entry;", "p.entryTime = (datetime)PositionGetInteger(POSITION_TIME); p.best = p.entry; p.reg = -1;")
rep('   PrintFormat("[SAAD-META] vetoed %d trades',
    '   PrintFormat("[SAAD-REGIME] mode %d: candles TREND %d / CHOP %d / NORMAL %d (ids trend %d chop %d)", InpRegimeMode, g_regBars[REG_TREND], g_regBars[REG_CHOP], g_regBars[3 - REG_TREND - REG_CHOP], REG_TREND, REG_CHOP);\n'
    '   if (g_regLog != INVALID_HANDLE) FileClose(g_regLog);\n'
    '   PrintFormat("[SAAD-META] vetoed %d trades')
