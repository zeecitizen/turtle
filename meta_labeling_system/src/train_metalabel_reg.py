"""Meta-labeling, REGRESSION variant (Zee 2026-10-13): predict the trade's net $ instead of win/lose.

Same data as train_metalabel.py (what Saad_meta logged in the Strategy Tester; no mock data):
    target y = the trade's final net $ (50% partial + runner + swap + $4/lot)
    weights  = |net $| (--weight abs, the suggestion) or none (--weight none)
    XGBRegressor reg:squarederror; veto a trade when the predicted $ < threshold.
The threshold is picked inside the training window (time-series CV, by the summed net of the
approved trades). The model is exported to MQL5 the same way: the EA's MetaModelProb() then
returns predicted $ and InpMetaThr is a $ amount (e.g. InpMetaThr=0).

A Python replay is a HYPOTHESIS. Only the MT5 tester run on the unseen period promotes.
    py train_metalabel_reg.py [--tag 1] [--cutoff 2026-07-01] [--weight abs|none] [--depth 3] [--trees 300] [--name reg]"""
import argparse, json, shutil, sys
from pathlib import Path
import numpy as np
import pandas as pd
import xgboost as xgb
import joblib
from sklearn.model_selection import TimeSeriesSplit
from train_metalabel import load, META_NAMES, tree_eval, tree_mql, ROOT, REPO


def make_model(depth, trees):
    return xgb.XGBRegressor(n_estimators=trees, learning_rate=0.03, max_depth=depth, subsample=0.85,
                            colsample_bytree=0.85, min_child_weight=1, objective="reg:squarederror",
                            eval_metric="mae", random_state=42, n_jobs=1)


def weights(y, mode):
    return np.abs(y) + 1.0 if mode == "abs" else np.ones(len(y))


def pick_threshold(df, a):
    grid = [-500, -250, -100, 0, 100, 250, 500]
    tot = {t: 0.0 for t in grid}; kept = {t: 0 for t in grid}; base = 0.0; n = 0
    for tr, va in TimeSeriesSplit(n_splits=4).split(df):
        m = make_model(a.depth, a.trees).fit(df.loc[tr, META_NAMES], df.loc[tr, "net"], sample_weight=weights(df.loc[tr, "net"], a.weight))
        p = m.predict(df.loc[va, META_NAMES]); net = df.loc[va, "net"].to_numpy()
        base += net.sum(); n += len(va)
        for t in grid: tot[t] += net[p >= t].sum(); kept[t] += int((p >= t).sum())
    print(f"\n[+] Threshold inside the training window (4-fold time-series CV, {n} validation trades)")
    print(f"    take everything      : net {base:>10,.0f}  ({n} trades)")
    for t in grid: print(f"    predicted >= ${t:>5}  : net {tot[t]:>10,.0f}  ({kept[t]} trades)")
    best = max(grid, key=lambda t: tot[t])
    print(f"    -> ${best}  (Python replay of fixed trades: a HYPOTHESIS only)")
    return float(best), base, tot[best]


def export_mqh(model, thr, trained_txt, path, a):
    b = model.get_booster(); b.feature_names = META_NAMES
    trees = [json.loads(t) for t in b.get_dump(dump_format="json")]
    base = float(json.loads(b.save_config())["learner"]["learner_model_param"]["base_score"].strip("[]"))
    names = ",".join(f'"{n}"' for n in META_NAMES)
    out = [f"// SaadMetaModel.mqh - GENERATED by meta_labeling_system/src/train_metalabel_reg.py — do not edit.",
           f"// REGRESSION: MetaModelProb() returns the PREDICTED NET $ of the trade (set InpMetaThr in $, e.g. 0).",
           f"// XGBoost {xgb.__version__}: {len(trees)} trees, depth {a.depth}, weights {a.weight}, trained on {trained_txt}; suggested threshold ${thr:.0f}",
           f"#define META_NF {len(META_NAMES)}", f'#define META_TRAINED "{trained_txt} REG {a.weight}"',
           f"string META_NAMES[META_NF] = {{{names}}};"]
    for k, t in enumerate(trees):
        out.append(f"double MetaTree{k}(const double &f[])\n{{\n{tree_mql(t)}}}")
    body = "\n".join(f"   m += MetaTree{k}(f);" for k in range(len(trees)))
    out.append(f"double MetaModelProb(const double &f[])\n{{\n   double m = {base:.12g};\n{body}\n   return m;\n}}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return trees, base


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="1"); ap.add_argument("--cutoff", default="2026-07-01")
    ap.add_argument("--weight", default="abs", choices=["abs", "none"])
    ap.add_argument("--depth", type=int, default=3); ap.add_argument("--trees", type=int, default=300)
    ap.add_argument("--name", default="reg"); ap.add_argument("--threshold", type=float, default=None)
    a = ap.parse_args()
    df = load(a.tag)
    tr = df[df.time < a.cutoff].reset_index(drop=True); te = df[df.time >= a.cutoff].reset_index(drop=True)
    print(f"[+] train {len(tr)} trades (< {a.cutoff}), unseen {len(te)} | weights {a.weight}, depth {a.depth}, trees {a.trees}")
    thr, cv_base, cv_best = pick_threshold(tr, a)
    if a.threshold is not None: thr = a.threshold
    model = make_model(a.depth, a.trees).fit(tr[META_NAMES], tr["net"], sample_weight=weights(tr["net"], a.weight))
    trained_txt = f"{tr.time.min():%Y-%m-%d}..{tr.time.max():%Y-%m-%d} ({len(tr)} trades)"
    (ROOT / "models").mkdir(exist_ok=True)
    joblib.dump({"model": model, "features": META_NAMES, "threshold": thr, "kind": "reg", "trained": trained_txt},
                ROOT / "models" / f"meta_model_xauusd_{a.name}.pkl")
    mqh = REPO / "mt5" / f"SaadMetaModel_{a.name}.mqh"
    trees, base = export_mqh(model, thr, trained_txt, mqh, a)
    shutil.copy(mqh, ROOT / "mql5" / mqh.name)
    X = df[META_NAMES].to_numpy(); px = model.predict(df[META_NAMES])
    pdump = np.array([base + sum(float(tree_eval(t, x)) for t in trees) for x in X])
    gap = float(np.abs(px - pdump).max())
    print(f"\n[+] parity xgboost vs exported trees: max |diff| = ${gap:.2e}  {'OK' if gap < 1e-2 else 'MISMATCH - do not use the .mqh'}")
    big = te.net.nlargest(5)
    p = model.predict(te[META_NAMES]); k = p >= thr
    print(f"[+] Python replay on the unseen period at predicted >= ${thr:.0f} (fixed trades - NOT what MT5 will do):")
    print(f"    all {len(te)} net {te.net.sum():,.0f} | approved {k.sum()} net {te.net[k].sum():,.0f} | vetoed {(~k).sum()} net {te.net[~k].sum():,.0f}")
    print(f"    the 5 biggest unseen winners {', '.join(f'${v:,.0f}' for v in big)}: approved {int(k[big.index].sum())} of 5")
    print("    NOT PROMOTED. Only MT5 decides.")
    print(f"\n[+] saved models/meta_model_xauusd_{a.name}.pkl and {mqh}")
