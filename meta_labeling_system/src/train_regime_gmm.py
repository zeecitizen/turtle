"""Market-regime GMM for Saad_strategy_15min (Zee 2026-10-13, "Option 2: Unsupervised Market Regime Detection").

Reads ONLY what the EA logged in the Strategy Tester (Saad_regime.mq5, InpRegimeLog=true): for every
closed M15 candle, Kaufman ER(14), ATR14/ATR200 and the 14-candle realized volatility. No mock data.
Fits StandardScaler + GaussianMixture(3, full covariance) on candles before --cutoff only, names the
clusters (highest mean ER = TREND, lowest = CHOP, the other = NORMAL), and writes:
    models/regime_gmm_xauusd.pkl     scaler + GMM + ids (for regime_server.py)
    mt5/SaadRegimeModel.mqh          the same GMM as MQL5 code, so the Strategy Tester can judge it
The regime only changes the EA's settings (see Saad_regime.mq5); it never vetoes a signal by itself.
    py train_regime_gmm.py [--tag 3] [--cutoff 2026-07-01] [--seed 42]"""
import argparse, shutil, sys
from pathlib import Path
import numpy as np
import pandas as pd
import joblib
from sklearn.mixture import GaussianMixture
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
COMMON = Path.home() / "AppData/Roaming/MetaQuotes/Terminal/Common/Files"
FEATS = ["kaufman_er", "atr_ratio", "realized_vol"]
NAMES = {}


def regime_of(x, sc_mean, sc_scale, w, mu, pchol):
    """Exactly what the MQL5 code computes: argmax_k log w_k + log|L_k| - 0.5 |(z - mu_k) L_k|^2."""
    z = (x - sc_mean) / sc_scale
    best, arg = -1e300, -1
    for k in range(len(w)):
        y = (z - mu[k]) @ pchol[k]
        lp = np.log(w[k]) + np.log(np.diag(pchol[k])).sum() - 0.5 * (y @ y)
        if lp > best: best, arg = lp, k
    return arg


def export_mqh(sc, g, trend, chop, trained, path):
    f = lambda a: ", ".join(f"{v:.17g}" for v in np.ravel(a))
    K = len(g.weights_)
    lines = [f"// SaadRegimeModel.mqh - GENERATED by meta_labeling_system/src/train_regime_gmm.py — do not edit.",
             f"// GMM {K} components (full covariance) on [ER14, ATR14/ATR200, realized vol 14], trained {trained}",
             f"#define REG_TREND {trend}", f"#define REG_CHOP {chop}", f'#define REG_TRAINED "{trained}"',
             f"double REG_SC_MEAN[3] = {{{f(sc.mean_)}}};", f"double REG_SC_SCALE[3] = {{{f(sc.scale_)}}};",
             f"double REG_W[{K}] = {{{f(g.weights_)}}};", f"double REG_MU[{K * 3}] = {{{f(g.means_)}}};",
             f"double REG_PCHOL[{K * 9}] = {{{f(g.precisions_cholesky_)}}};   // [k][row][col]",
             "int RegimeOf(const double &x[])",
             "{",
             "   double z[3]; for (int j = 0; j < 3; j++) z[j] = (x[j] - REG_SC_MEAN[j]) / REG_SC_SCALE[j];",
             "   double best = -1e300; int arg = -1;",
             f"   for (int k = 0; k < {K}; k++) {{",
             "      double lp = MathLog(REG_W[k]), q = 0;",
             "      for (int c = 0; c < 3; c++) {",
             "         double y = 0;",
             "         for (int r = 0; r < 3; r++) y += (z[r] - REG_MU[k * 3 + r]) * REG_PCHOL[k * 9 + r * 3 + c];",
             "         q += y * y;",
             "         lp += MathLog(REG_PCHOL[k * 9 + c * 3 + c]);",
             "      }",
             "      lp -= 0.5 * q;",
             "      if (lp > best) { best = lp; arg = k; }",
             "   }",
             "   return arg;",
             "}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="3"); ap.add_argument("--cutoff", default="2026-07-01"); ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args()
    src = COMMON / f"saad_regime_{a.tag}.csv"
    if not src.exists():
        sys.exit(f"missing {src}\nRun Saad_regime in the Strategy Tester with InpRegimeLog=true, InpMetaTag={a.tag} first.")
    (ROOT / "data").mkdir(exist_ok=True); shutil.copy(src, ROOT / "data" / "xauusd_m15_features.csv")
    df = pd.read_csv(src); df["time"] = pd.to_datetime(df["time"], format="%Y.%m.%d %H:%M")
    tr = df[df.time < a.cutoff]
    print(f"[+] {len(df)} candles logged; fitting on {len(tr)} before {a.cutoff}")
    sc = StandardScaler().fit(tr[FEATS])
    g = GaussianMixture(n_components=3, covariance_type="full", random_state=a.seed, max_iter=500, n_init=5).fit(sc.transform(tr[FEATS]))
    lab = g.predict(sc.transform(df[FEATS]))
    st = df.assign(reg=lab)[df.time < a.cutoff].groupby("reg")[FEATS].mean()
    trend, chop = int(st.kaufman_er.idxmax()), int(st.kaufman_er.idxmin())
    name = {trend: "TREND", chop: "CHOP"}; name[3 - trend - chop] = "NORMAL"
    st.index = [f"{i} {name[i]}" for i in st.index]
    share = pd.Series(lab).value_counts(normalize=True).sort_index()
    print("\n[+] cluster means (training candles):"); print(st.round(5).to_string())
    print("    share of all candles:", ", ".join(f"{name[k]} {v:.0%}" for k, v in share.items()))
    trained = f"{tr.time.min():%Y-%m-%d}..{tr.time.max():%Y-%m-%d} ({len(tr)} candles)"
    (ROOT / "models").mkdir(exist_ok=True)
    joblib.dump({"scaler": sc, "model": g, "features": FEATS, "trend_id": trend, "chop_id": chop, "trained": trained}, ROOT / "models" / "regime_gmm_xauusd.pkl")
    mqh = REPO / "mt5" / "SaadRegimeModel.mqh"
    export_mqh(sc, g, trend, chop, trained, mqh); shutil.copy(mqh, ROOT / "mql5" / mqh.name)
    mine = np.array([regime_of(x, sc.mean_, sc.scale_, g.weights_, g.means_, g.precisions_cholesky_) for x in df[FEATS].to_numpy()])
    print(f"\n[+] parity sklearn vs exported formula: {int((mine != lab).sum())} of {len(lab)} candles differ  {'OK' if (mine == lab).all() else 'MISMATCH'}")
    pd.DataFrame({"time": df.time, "regime": lab}).to_csv(ROOT / "data" / "python_regimes.csv", index=False)
    print(f"[+] saved models/regime_gmm_xauusd.pkl and {mqh}")
