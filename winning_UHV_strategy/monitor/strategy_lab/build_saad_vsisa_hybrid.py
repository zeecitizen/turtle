"""Build mt5/saad_vsisa_hybrid.mq5 v1.00 (Zee 2026-10-14: "pick the best variant and call this EA it
saad_vsisa_hybrid") from the research hybrid (build_hybrid.py + patch_hybrid_stats.py + patch_hybrid_blend.py).

The best variant (report §30-31): BOTH engines trade on their own; a Saad trade is taken at 2x lots when VSISA
opened a same-direction trade within the last 60 minutes. MT5 (XAUUSD_TK, random delay): Jul-Oct +$88,194
(net/DD 7.26 vs 6.43 side by side), full year +$241,320 (21.45 vs 19.57).
Run the three research scripts first, then this one."""
from pathlib import Path

M = Path(r'C:\Users\zeesh\turtle\mt5')
VER = "1.00"
C = f"SVHyb v{VER}"           # trade comment prefix (MT5 keeps 31 chars)

# ---- Saad engine copy with its own comment ------------------------------------------------------------------
e = (M / 'SaadEngine15.mqh').read_text(encoding='utf-8')


def rep_in(txt, a, b, n=1):
    assert txt.count(a) == n, (txt.count(a), a[:70])
    return txt.replace(a, b)


e = rep_in(e, '#define S_EA_COMMENT "Hyb-Saad15 probe"', f'#define S_EA_COMMENT "{C} SAAD"')
e = rep_in(e, 'S_EA_COMMENT + " BUY")', 'S_EA_COMMENT + HybTag() + " BUY")')
e = rep_in(e, 'S_EA_COMMENT + " SELL")', 'S_EA_COMMENT + HybTag() + " SELL")')
e = rep_in(e, 'input group "=== Saad 15-min PROBE engine (v1.18 rules, M15) ==="',
           'input group "=== Saad 15-min engine (v1.18 rules, M15 candles) ==="')
e = rep_in(e, 'input int    S_InpMagicNumber = 88340;', 'input int    S_InpMagicNumber = 88350;')
e = e.replace('SaadEngine15.mqh - GENERATED by monitor/strategy_lab/build_hybrid.py from |',
              'saad_vsisa_hybrid_saad.mqh - GENERATED (build_saad_vsisa_hybrid.py) from |')
(M / 'saad_vsisa_hybrid_saad.mqh').write_text(e, encoding='utf-8')

# ---- the EA ---------------------------------------------------------------------------------------------------
s = (M / 'Hybrid_Saad15_VSISA5.mq5').read_text(encoding='utf-8')
s = rep_in(s, '#include "SaadEngine15.mqh"', '#include "saad_vsisa_hybrid_saad.mqh"')
s = rep_in(s, 'input int    InpMagicNumber = 88341;', 'input int    InpMagicNumber = 88351;')
s = rep_in(s, 'input group "=== HYBRID: VSISA adds only behind a mature Saad probe ==="',
           'input group "=== saad_vsisa_hybrid: both trade; Saad x2 lots when VSISA traded the same way <= 60 min ==="')
for a, b in [('input bool   InpHybNeedProbe = true;', 'input bool   InpHybNeedProbe = false;'),
             ('input int    InpHybSaadGate = 0;', 'input int    InpHybSaadGate = 2;'),
             ('input int    InpHybSaadAct  = 0;', 'input int    InpHybSaadAct  = 1;'),
             ('input int    InpHybWinMin   = 240;', 'input int    InpHybWinMin   = 60;')]:
    s = rep_in(s, a, b)
assert 'input double InpHybConfMult = 2.0;' in s
# boosted Saad trades say so in their comment
s = rep_in(s, 'double HybSaadLots(int side, double lots)\n{\n',
           'bool g_hBoostNow = false;\nstring HybTag() { return g_hBoostNow ? " x2" : ""; }\n'
           'double HybSaadLots(int side, double lots)\n{\n   g_hBoostNow = false;\n')
s = rep_in(s, '   g_hSaadBoosted++;\n', '   g_hSaadBoosted++; g_hBoostNow = true;\n')
s = rep_in(s, 'string tag = StringFormat("vsisa_%d_%d", g_fires, i);',
           f'string tag = StringFormat("{C} VSISA %d_%d", g_fires, i);')
s = s.replace('PrintFormat("[HYBRID Saad15xVSISA5] v1.00 | VSISA part v1.30 (ML:',
              f'PrintFormat("[HYBRID Saad15xVSISA5] saad_vsisa_hybrid v{VER} | VSISA part v1.30 (ML:')
s = rep_in(s, '#property version   "1.00"', f'#property version   "{VER}"')
s = s.replace('//| Hybrid_Saad15_VSISA5.mq5 v1.00 (2026-10-14) - attach on XAUUSD M5. |',
              f'//| saad_vsisa_hybrid.mq5 v{VER} (2026-10-14) - attach on XAUUSD M5.   |', 1)
s = ('//+------------------------------------------------------------------+\n'
     f'//| saad_vsisa_hybrid v{VER}: Saad 15-min (v1.18, magic 88350) and VSISA |\n'
     '//| 5-min (v1.30, magic 88351) in ONE EA. Both trade on their own; a  |\n'
     '//| Saad trade opens at 2x lots (comment "x2") when VSISA opened a    |\n'
     '//| same-direction trade within the last 60 minutes. Needs, next to  |\n'
     '//| it: saad_vsisa_hybrid_saad.mqh + the four Vsisa*.mqh model files. |\n'
     '//| GENERATED by monitor/strategy_lab/build_saad_vsisa_hybrid.py.      |\n'
     '//+------------------------------------------------------------------+\n') + s
(M / 'saad_vsisa_hybrid.mq5').write_text(s, encoding='utf-8')
print('saad_vsisa_hybrid built')
