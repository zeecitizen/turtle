"""Build the Saad x VSISA hybrid (Zee 2026-10-14: "a new hybrid EA which uses the 15 minute saad EA to open a probe
trade. When that trade becomes sufficiently mature, the EA looks for the 5 minute VSISA setup and executes by
pyramidding").
  1. mt5/SaadEngine15.mqh  = Saad_strategy_15min v1.18 with every top-level name prefixed S_ (so it can live beside
     VSISA in one EA), its timeframe fixed to M15 (PERIOD_CURRENT -> PERIOD_M15), drawing/logging off by default.
  2. mt5/Hybrid_Saad15_VSISA5.mq5 = VSISA v1.30 (M5 chart) + the Saad engine: Saad opens the PROBE (magic 88340);
     VSISA may only fire while a same-direction probe is open and mature (InpHybMature), its trades are the pyramid
     adds (magic 88341)."""
import re
from pathlib import Path

M = Path(r'C:\Users\zeesh\turtle\mt5')
saad = (M / 'Saad_strategy_15min.mq5').read_text(encoding='utf-8').replace('\ufeff', '')

# ---- 1. the Saad engine ---------------------------------------------------------------------------------------
body = saad[saad.index('#include <Trade/Trade.mqh>'):]
body = body.replace('#include <Trade/Trade.mqh>\n', '')
names = set()
names |= set(re.findall(r'^input\s+\w+\s+(\w+)', body, re.M))
names |= set(re.findall(r'^struct\s+(\w+)', body, re.M))
names |= set(re.findall(r'^#define\s+(\w+)', body, re.M))
for m in re.finditer(r'^(?:static\s+)?(?:const\s+)?[A-Za-z_]\w*(?:\s*\[\])?\s+[A-Za-z_]\w*\s*\(', body, re.M):  # functions
    names.add(re.search(r'([A-Za-z_]\w*)\s*\($', m.group(0)).group(1))
for m in re.finditer(r'^(?:int|double|bool|string|datetime|ulong|long|uint|color|CTrade|PosState)\s+([^;(]+);', body, re.M):   # globals
    for part in m.group(1).split(','):
        nm = re.match(r'\s*([A-Za-z_]\w*)', part)
        if nm: names.add(nm.group(1))
names -= {'if', 'for', 'while', 'switch', 'return', 'else'}
for n in sorted(names, key=len, reverse=True):
    body = re.sub(rf'(?<![\w.]){n}\b', 'S_' + n, body)
body = body.replace('PERIOD_CURRENT', 'PERIOD_M15').replace('PeriodSeconds()', 'PeriodSeconds(PERIOD_M15)')
body = re.sub(r'#define S_EA_COMMENT "[^"]*"', '#define S_EA_COMMENT "Hyb-Saad15 probe"', body)
# engine defaults for the hybrid: own magic, quiet chart/log
body = re.sub(r'(input int    S_InpMagicNumber = )88302;', r'\g<1>88340;', body)
body = re.sub(r'(input bool   S_InpDraw      = )true;', r'\g<1>false;', body)
body = re.sub(r'(input bool   S_InpLog       = )true;', r'\g<1>false;', body)
body = re.sub(r'(input bool   S_InpLogCsv    = )true;', r'\g<1>false;', body)
hdr = ('//+------------------------------------------------------------------+\n'
       '//| SaadEngine15.mqh - GENERATED by monitor/strategy_lab/build_hybrid.py from |\n'
       '//| Saad_strategy_15min.mq5 v1.18: every name prefixed S_, timeframe = M15.   |\n'
       '//| Do not edit; rebuild instead.                                              |\n'
       '//+------------------------------------------------------------------+\n'
       'input group "=== Saad 15-min PROBE engine (v1.18 rules, M15) ==="\n')
(M / 'SaadEngine15.mqh').write_text(hdr + body, encoding='utf-8')
print(f'engine: {len(names)} names prefixed')

# ---- 2. the hybrid EA -------------------------------------------------------------------------------------------
v = (M / 'VSISA.mq5').read_text(encoding='utf-8').replace('\ufeff', '')


def rep(a, b):
    global v
    assert v.count(a) == 1, (v.count(a), a[:70])
    v = v.replace(a, b)


rep('#include "VsisaDrlPolicy.mqh"', '#include "VsisaDrlPolicy.mqh"\n#include "SaadEngine15.mqh"')
rep('input group "=== Machine learning', '''input group "=== HYBRID: VSISA adds only behind a mature Saad probe ==="
input bool   InpHybSaad     = true;   // InpHybSaad — run the Saad 15-min probe engine
input bool   InpHybVsisa    = true;   // InpHybVsisa — run the VSISA 5-min add engine (needs a probe)
input int    InpHybMature   = 1;      // InpHybMature — probe maturity before VSISA may add: 0 just open · 1 in profit >= InpHybMatureR x its risk · 2 stop at/after breakeven (CTC/TP1)
input double InpHybMatureR  = 0.5;    // InpHybMatureR — mode 1: open profit in R
input bool   InpHybCloseAdds = false; // InpHybCloseAdds — close the VSISA adds when the probe closes
input bool   InpHybNeedProbe = true;  // InpHybNeedProbe — false = VSISA trades freely (benchmark: both EAs side by side)
input group "=== Machine learning''')
rep('input int    InpMagicNumber = 88201;', 'input int    InpMagicNumber = 88341;')
# the gate: at the top of Fire
rep('void Fire(int side, double sl_level, string why) {\n',
    '''// --- hybrid gate: a same-direction Saad probe that is mature enough ---
int g_hybBlocked = 0, g_hybAllowed = 0;
bool HybProbeOk(int side)
{
   if (!InpHybNeedProbe) return true;
   for (int i = PositionsTotal() - 1; i >= 0; i--) {
      ulong t = PositionGetTicket(i);
      if (t == 0 || PositionGetInteger(POSITION_MAGIC) != S_InpMagicNumber || PositionGetString(POSITION_SYMBOL) != _Symbol) continue;
      int sd = PositionGetInteger(POSITION_TYPE) == POSITION_TYPE_BUY ? 1 : -1;
      if (sd != side) continue;
      double en = PositionGetDouble(POSITION_PRICE_OPEN), sl = PositionGetDouble(POSITION_SL);
      double px = sd > 0 ? SymbolInfoDouble(_Symbol, SYMBOL_BID) : SymbolInfoDouble(_Symbol, SYMBOL_ASK);
      double risk = 0;
      for (int k = 0; k < ArraySize(S_g_pos); k++) if (S_g_pos[k].ticket == t) risk = MathAbs(S_g_pos[k].entry - S_g_pos[k].sl0);
      if (risk <= 0) risk = sl > 0 ? MathAbs(en - sl) : 0;
      if (InpHybMature == 0) return true;
      if (InpHybMature == 1 && risk > 0 && sd * (px - en) >= InpHybMatureR * risk) return true;
      if (InpHybMature == 2 && sl > 0 && (sd > 0 ? sl >= en : sl <= en)) return true;
   }
   return false;
}
void Fire(int side, double sl_level, string why) {
   if (!HybProbeOk(side)) { g_hybBlocked++; return; }
   g_hybAllowed++;
''')
rep('void OnTick() {\n   MlTick();\n', '''void HybCloseAdds()
{
   if (!InpHybCloseAdds) return;
   bool probe = false;
   for (int i = PositionsTotal() - 1; i >= 0; i--) { ulong t = PositionGetTicket(i); if (t > 0 && PositionGetInteger(POSITION_MAGIC) == S_InpMagicNumber && PositionGetString(POSITION_SYMBOL) == _Symbol) probe = true; }
   if (probe) return;
   for (int i = PositionsTotal() - 1; i >= 0; i--) { ulong t = PositionGetTicket(i); if (t > 0 && PositionGetInteger(POSITION_MAGIC) == InpMagicNumber && PositionGetString(POSITION_SYMBOL) == _Symbol) trade.PositionClose(t); }
}
void OnTick() {
   if (InpHybSaad) S_OnTick();
   HybCloseAdds();
   if (!InpHybVsisa) return;
   MlTick();
''')
rep('int OnInit() {\n', 'int OnInit() {\n   if (InpHybSaad && S_OnInit() != INIT_SUCCEEDED) return INIT_FAILED;\n')
rep('void OnDeinit(const int reason) {\n', 'void OnDeinit(const int reason) {\n   if (InpHybSaad) S_OnDeinit(reason);\n   PrintFormat("[HYBRID] VSISA setups allowed (probe mature) %d, blocked (no mature probe) %d", g_hybAllowed, g_hybBlocked);\n')
v = v.replace('#property version   "1.30"', '#property version   "1.00"')
v = v.replace('PrintFormat("[VSISA] v1.30 (ML:', 'PrintFormat("[HYBRID Saad15xVSISA5] v1.00 | VSISA part v1.30 (ML:')
head = ('//+------------------------------------------------------------------+\n'
        '//| Hybrid_Saad15_VSISA5.mq5 v1.00 (2026-10-14) - attach on XAUUSD M5. |\n'
        '//| The Saad 15-min engine (v1.18 rules, on M15 candles) opens the     |\n'
        '//| PROBE trade (magic 88340). VSISA (v1.30, M5) may only fire while a |\n'
        '//| same-direction probe is open and mature (InpHybMature); its trades |\n'
        '//| are the pyramid adds (magic 88341).                                |\n'
        '//+------------------------------------------------------------------+\n')
(M / 'Hybrid_Saad15_VSISA5.mq5').write_text(head + v, encoding='utf-8')
print('hybrid written')
