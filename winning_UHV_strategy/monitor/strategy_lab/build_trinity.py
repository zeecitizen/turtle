def setdef(txt, name, val):
    pat = re.compile(rf'^(input\s+\w+\s+{name}\s*=\s*)([^;]+);', re.M)
    assert len(pat.findall(txt)) == 1, name
    return pat.sub(lambda m: m.group(1) + val + ';', txt)


def engine(src_file, P, tf, magic, title, defaults, comment_fix=None):
    src = (M / src_file).read_text(encoding='utf-8').replace('\ufeff', '')
    body, names = prefix_engine(src, P)
    tfv = f'{P}InpTF'
    body = (body.replace('PeriodSeconds()', f'PeriodSeconds({tfv})').replace('PERIOD_CURRENT', tfv)
            .replace('(ENUM_TIMEFRAMES)Period()', tfv).replace('Period()', tfv).replace('_Period', tfv))
    body = setdef(body, f'{P}InpMagicNumber', str(magic))
    for k, v in defaults.items():
        body = setdef(body, P + k, v)
    if comment_fix:
        body = comment_fix(body)
    hdr = (f'//+------------------------------------------------------------------+\n'
           f'//| {src_file} as an engine for Trinity_1min - GENERATED by build_trinity.py |\n'
           f'//| every top-level name prefixed {P}, timeframe = input {tfv}.       |\n'
           f'//+------------------------------------------------------------------+\n'
           f'input group "=== {title} ==="\n'
           f'input ENUM_TIMEFRAMES {tfv} = {tf};   // {tfv} — this engine\'s candles\n')
    return hdr + body, names


