"""bread_winner v1.00 - the shipped one-shot EA, generated from the research build bread_winner_shot.mq5
(build_bread_shot.py + build_bws_pb.py) with the winning policy baked in as DEFAULTS (report §36):
  scouts: Diamond (only from PKT 17:00) + VSISA (looser: campaign >= 60% of max, >= 1.0x avg, reaction body >= 25%,
          raw signal)   ·   ONE shot per Pakistan day, any hour   ·   0.12 lots, TP $1 (= ~$11.52), SL $8 (v1.01)
Own engine files (bread_*.mqh) and magics 88390-88394, comments "Bread v1.00 ..."."""
import re
from pathlib import Path

M = Path(r'C:\Users\zeesh\turtle\mt5')
VER = "1.03"


def setdef(txt, name, val):
    pat = re.compile(rf'^(input\s+(\w+)\s+{name}\s*=\s*)([^;]+);', re.M)
    assert len(pat.findall(txt)) == 1, name
    return pat.sub(lambda m: m.group(1) + val + ';', txt)


eng = {}
for f in ('saad', 'vsisa', 'dia', 'pb', 'vsisa2'):
    eng[f] = (M / f'bws_{f}.mqh').read_text(encoding='utf-8').replace('as a signal scout for bread_winner', f'bread_winner v{VER} scout')
eng["dia"] = setdef(eng["dia"], "D_InpLots", "0.12")
for k, v in (('V_InpBigPct', '0.60'), ('V_InpBigAvg', '1.00'), ('V_InpBodyFrac', '0.25'), ('V_InpVerbose', 'false')):
    eng['vsisa'] = setdef(eng['vsisa'], k, v)
for f, t in eng.items():
    (M / f'bread_{f}.mqh').write_text(t.replace('Bread v1.00', f'Bread v{VER}'), encoding='utf-8')

h = (M / 'bread_winner_shot.mq5').read_text(encoding='utf-8')
for f in ('saad', 'vsisa', 'dia', 'pb', 'vsisa2'):
    h = h.replace(f'#include "bws_{f}.mqh"', f'#include "bread_{f}.mqh"')
for k, v in (('InpTrig', '37'), ('InpPbFrom', '22'), ('InpShotMax', '1'), ('InpWinFrom', '0'), ('InpWinTo', '24'), ("InpShotLots", "0.12"),
             ('InpShotTp', '1.0'), ("InpShotSl", "8.0"), ('InpShotLog', 'false'), ('InpVsLate', 'false'), ('InpDiaFrom', '17'),
             ('InpCtxMask', '0'), ('InpUseSaad', 'false'), ('InpUsePb', 'true'), ('InpUseVs2', 'false')):
    h = setdef(h, k, v)
# v1.03 (Zee, 2026-10-14): the New York 8:00-8:45 AM BURST trigger as a filler for days with no shot yet (report §38)
from bread_ny_patch import apply_ny
h = apply_ny(h)
for k, v in (('InpTrig', '165'), ('InpNyMode', '2'), ('InpNyBody', '60'), ('InpNyAtr', '1.5'), ('InpNyCtx', 'false')):
    h = setdef(h, k, v)
_smc = '      // InpShotMax — shots per day (1 = one perfect shot)'
assert h.count(_smc) == 1
h = h.replace(_smc, '').replace('input int    InpShotMax     = 1;\n', 'input int    InpShotMax     = 1;' + _smc + '\n')
h = h.replace('RESEARCH NY-momentum trigger', 'NY-momentum trigger').replace('trig == 4 ? "PULSE"', 'trig == 4 ? "NYBURST"')
h = re.sub(r'^//\+-+\+\n(//\|.*\n)+//\+-+\+\n', '', h, count=1)
h = (f'//+------------------------------------------------------------------+\n'
     f'//| bread_winner.mq5 v{VER} (2026-10-14) - attach on XAUUSD (any chart).|\n'
     '//| ONE shot per Pakistan day: the first Diamond UHV breakout (after   |\n'
     '//| PKT 17:00), VSISA low-volume reaction, or - only after PKT 22:00 - |\n'
     '//| a VSISA pullback (fallback); v1.03: or, 8:00-8:45 AM New York, a   |\n'
     '//| big momentum minute (NY BURST). 0.12 lots, TP $1 = ~$11.5,         |\n'
     '//| SL $8. Then it waits for tomorrow. Report: report.md section 36.  |\n'
     '//| Needs bread_saad/vsisa/dia/pb.mqh + the 4 Vsisa*.mqh files.        |\n'
     '//| GENERATED by monitor/strategy_lab/build_bread_final.py.            |\n'
     '//+------------------------------------------------------------------+\n') + h
h = re.sub(r'#property version\s+"[^"]*"', f'#property version   "{VER}"', h, count=1)
h = h.replace('[BREAD] bread_winner_shot', f'[BREAD] bread_winner v{VER}')
h = h.replace('"Bread 1.00 ', f'"Bread v{VER} ')
(M / 'bread_winner.mq5').write_text(h, encoding='utf-8')
print('bread_winner built')
